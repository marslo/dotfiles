#!/usr/bin/env bash
#=============================================================================
#     FileName : npm-flags.bash
#       Author : marslo
#      Created : 2026-10-26 18:02:27
#   LastChange : 2026-10-26 18:53:17
#  Description : npm bash completion entry: sources npm.bash ( `npm completion`, via update.sh ) and adds `-` / `--` flag completion on top
#                takes over the `_npm_completion` name ( npm's own renamed to `__npm_completion_orig` ), so any `complete -F _npm_completion npm` lands here
#                subcommand flags from `npm <cmd> --help` Options, global flags from `npm config ls -l` keys
#                resolved on first <TAB> per subcommand, cached per npm version in ${XDG_CACHE_HOME:-~/.cache}/npm-flags/v2/<npm-version>/; short opts listed first
#=============================================================================

declare -gA _NPM_FLAGS=()

# npm's own completion ( generated by update.sh )
# shellcheck source=/dev/null
test -f "${BASH_SOURCE[0]%/*}/npm.bash" && source "${BASH_SOURCE[0]%/*}/npm.bash"
# rename npm's `_npm_completion` to `__npm_completion_orig`; skipped when `_npm_completion` is already this wrapper
if declare -F _npm_completion >/dev/null && ! declare -f _npm_completion | command grep -q '__npm_completion_orig'; then
  eval "__npm_completion_orig() $( declare -f _npm_completion | tail -n +2 )"
fi

# print the running npm version from its package.json ( fallback: `npm --version` )
__npm_flags_version() {
  local cli ver=''
  cli="$( command realpath "$( type -P npm )" 2>/dev/null )" \
    && ver="$( sed -nE 's/^[[:space:]]*"version":[[:space:]]*"([^"]+)".*/\1/p' "${cli%/bin/*}/package.json" 2>/dev/null | head -1 )"
  echo "${ver:-$( command npm --version 2>/dev/null )}"
}

# dedupe stdin flags and order short opts ( `-g` ) before long opts ( `--global` ), each alphabetically
__npm_flags_order() {
  sort -u | awk '{ print ( /^--/ ? 1 : 0 ) "\t" $0 }' | sort -t$'\t' -k1,1n -k2,2 | cut -f2
}

# load the flags of <cmd> ( `__global__` for npm configs ) into _NPM_FLAGS[<cmd>], via the on-disk cache
__npm_flags_load() {
  local cmd="${1}" file flags
  test -v "_NPM_FLAGS[${cmd}]" && return 0
  test -n "${_NPM_FLAGS_CACHE:-}" || _NPM_FLAGS_CACHE="${XDG_CACHE_HOME:-${HOME}/.cache}/npm-flags/v2/$( __npm_flags_version )"
  file="${_NPM_FLAGS_CACHE}/${cmd}"

  if ! test -f "${file}"; then
    if test '__global__' = "${cmd}"; then
      # short opts from every command's Options ( `npm -l` ) + config keys as long opts
      flags="$( { printf '%s\n' -h -v --help --version
                  command npm -l 2>/dev/null | command grep -oE -- '\[-[A-Za-z]+\|' | tr -d '[|'
                  command npm config ls -l 2>/dev/null | awk '/^[a-z][a-z0-9-]* = / { print "--" $1 }'
                } | __npm_flags_order )"
    else
      flags="$( command npm "${cmd}" --help 2>/dev/null \
                  | awk '/^Options:/ { on = 1; next } on && /^$/ { exit } on { gsub( /<[^>]*>/, "" ); print }' \
                  | command grep -oE -- '--?[A-Za-z][A-Za-z0-9-]*' )"
      test -n "${flags}" && flags="$( printf '%s\n' -h --help "${flags}" | __npm_flags_order )"
    fi
    mkdir -p "${_NPM_FLAGS_CACHE}" 2>/dev/null && printf '%s\n' "${flags}" > "${file}"
  else
    flags="$( < "${file}" )"
  fi
  _NPM_FLAGS[${cmd}]="${flags//$'\n'/ }"
}

# complete `-` / `--` from the subcommand's options ( else global configs ); defer everything else to npm's `__npm_completion_orig`
_npm_completion() {
  local cur="${COMP_WORDS[COMP_CWORD]}" cmd='__global__' i
  if [[ "${cur}" != -* ]]; then
    __npm_completion_orig "${@}"
    return
  fi
  for (( i = 1; i < COMP_CWORD; i++ )); do
    [[ "${COMP_WORDS[i]}" == -* ]] || { cmd="${COMP_WORDS[i]}"; break; }
  done
  [[ "${cmd}" =~ ^[A-Za-z0-9][A-Za-z0-9-]*$ ]] || cmd='__global__'
  __npm_flags_load "${cmd}"
  [[ -n "${_NPM_FLAGS[${cmd}]// /}" ]] || { cmd='__global__'; __npm_flags_load "${cmd}"; }
  # keep the cached order ( short opts first ) instead of readline's alphabetical sort
  compopt -o nosort 2>/dev/null
  mapfile -t COMPREPLY < <( compgen -W "${_NPM_FLAGS[${cmd}]}" -- "${cur}" )
}

declare -F __npm_completion_orig >/dev/null && complete -o default -F _npm_completion npm

